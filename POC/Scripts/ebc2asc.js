// Função de conversão
function convertEBCDICtoASCII(buffer) {
  let asciiBuffer = "";
  for (let i = 0; i < buffer.length; i++) {
    const ebcdicByte = buffer[i];
    if (ebcdicByte === 0x8b) {
      asciiBuffer += "\r1 ";
    } else if (ebcdicByte === 0x09) {
      asciiBuffer += "\r ";
    } else if (ebcdicByte === 0x19) {
      asciiBuffer += "\r-";
    } else {
      const asciiByte = ebcdicToAscii[ebcdicByte];
      asciiBuffer += String.fromCharCode(asciiByte);
    }
  }
  return asciiBuffer;
}

// Obter parâmetros da linha de comando
const [, , inputFile, outputFile] = process.argv;

if (!inputFile || !outputFile) {
  console.error("Uso: node ebc2asc.js <arquivo_entrada> <arquivo_backup>");
  console.error("Se o input for ASCII, o arquivo não será modificado.");
  console.error(
    "Sendo EBCDIC, o arquivo original será salvo como <arquivo_backup> e o arquivo de entrada será convertido para ASCII."
  );
  process.exit(1);
}

// Abrir o arquivo e ler os primeiros 256 bytes
fs.open(inputFile, "r", (err, fd) => {
  if (err) {
    console.error(`Erro ao abrir ${inputFile}:`, err.message);
    process.exit(1);
  }

  const buffer = Buffer.alloc(256);
  fs.read(fd, buffer, 0, 256, 0, (err, bytesRead) => {
    if (err) {
      console.error(`Erro ao ler ${inputFile}:`, err.message);
      fs.close(fd, () => {});
      process.exit(1);
    }

    // Verificar sequência de 4 bytes 0x40
    let found = false;
    for (let i = 0; i <= bytesRead - 4; i++) {
      if (buffer[i] === 0x40 && buffer[i + 1] === 0x40 && buffer[i + 2] === 0x40 && buffer[i + 3] === 0x40) {
        found = true;
        break;
      }
    }

    if (!found) {
      console.log(`${inputFile} é ASCII e não requer conversão.`);
      fs.close(fd, () => {
        process.exit(0);
      });
    }

    fs.close(fd, () => {
      // Ler o arquivo completo e converter
      console.log(`Convertendo ${inputFile}...`);
      fs.readFile(inputFile, (err, ebcdicData) => {
        if (err) {
          console.error(`Erro ao ler ${inputFile}:`, err.message);
          process.exit(1);
        }
        const asciiData = convertEBCDICtoASCII(ebcdicData);
        try {
          fs.renameSync(inputFile, outputFile);
          console.log(`Arquivo original ${inputFile} salvo como ${outputFile}.`);
        } catch (err) {
          console.error("Erro ao renomear:", err.message);
        }
        fs.writeFile(inputFile, asciiData, (err) => {
          if (err) {
            console.error(`Erro ao gravar resultado ASCII em ${inputFile}:`, err.message);
            process.exit(1);
          }
          console.log(`${inputFile} convertido para ASCII com sucesso.`);
        });
      });
    });
  });
});
